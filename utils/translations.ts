// Global Event Bus for Language
const listeners = new Set<(lang: Language) => void>();
let currentLang: Language = 'en';

export const getCurrentLanguage = (): Language => currentLang;

export const setLanguage = (lang: Language) => {
  currentLang = lang;
  document.documentElement.dir = lang === 'fa' ? 'rtl' : 'ltr';
  document.documentElement.lang = lang;
  // Apply font based on language
  document.body.style.fontFamily = lang === 'fa' ? '"Vazirmatn", sans-serif' : '"Inter", sans-serif';
  listeners.forEach(l => l(lang));
};

export const useTranslation = () => {
  const [lang, setLang] = useState<Language>(currentLang);

  useEffect(() => {
    const handler = (l: Language) => setLang(l);
    listeners.add(handler);
    return () => { listeners.delete(handler); };
  }, []);

  const toggleLanguage = () => {
      setLanguage(lang === 'en' ? 'fa' : 'en');
  };

  return {
    t: (key: keyof typeof translations['en'], vars?: Record<string, string>) => {
      let str = (translations[lang] || translations['en'] as any)[key] || key;
      if (vars) {
        Object.entries(vars).forEach(([k, v]) => {
          str = str.replace(`{${k}}`, v ?? '');
        });
      }
      return str;
    },
    dir: lang === 'fa' ? 'rtl' : 'ltr',
    lang,
    setLanguage,
    toggleLanguage
  };
};
